def print_solution(name, routes, total):
    best_known = 784
    gap = ((total - best_known) / best_known) * 100

    print("\n" + "=" * 50)
    print(name)
    print("=" * 50)

    for idx, r in enumerate(routes, start=1):
        print(f"\nVehicle {idx}")
        print("Route:", r)
        print("Load:", route_load(r))
        print("Distance:", route_cost(r))

    print("\nNumber of routes:", len(routes))
    print("Total distance:", total)
    print("Best known solution:", best_known)
    print(f"Gap: {gap:.2f}%")


sweep_routes, sweep_total = solve_sweep()
cw_routes, cw_total = solve_clarke_wright()
nn_routes, nn_total = solve_nearest_neighbour()


